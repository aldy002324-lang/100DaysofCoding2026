public class App {
    public static void main(String[] args) {
        float umur = 19f;
        double tinggi = 165.4;

        System.out.println("umur :" + umur);
        System.out.println("tinggi :" + tinggi);

        // tipe data float digunakan untuk menyimpan bilangan pecahan dengan ketelitian lebih rendah
        // huruf f dibelakang angka menandakan nilai float
        // tipe data double digunakan untuk menyimpan bilangan pecahan dengan ketelitian lebih tinggi

        // menampilkan nilai dari variabel float 
        // menampilkan nilai dari variabel double
    }
}
