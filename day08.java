public class App {
    public static void main(String[] args) {

        // Deklarasi variabel
        int umur;
        String nama;

        // Inisialisasi variabel
        umur = 19;
        nama = "Aldi";

        System.out.println("Nama : " + nama);
        System.out.println("Umur awal : " + umur);

        // Update variabel
        umur = 20;
        System.out.println("Umur setelah update : " + umur);
    }
}
