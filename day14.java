public class day14 {
    public static void main(String[] args) {

        int a = 20; // Nilai pertama
        int b = 8;  // Nilai kedua

        int penjumlahan = a + b; // Menjumlahkan a dan b
        int pengurangan = a - b; // Mengurangi a dengan b

        System.out.println("Hasil Penjumlahan = " + penjumlahan);
        System.out.println("Hasil Pengurangan = " + pengurangan);
    }
}
